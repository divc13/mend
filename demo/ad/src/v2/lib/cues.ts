import { interpolate, useCurrentFrame, useVideoConfig } from 'remotion';
import cueJson from '../cues.generated.json';
import { CLAMP } from '../../motion';
import { sceneById, v2Script, type SceneId } from './script';

export type Cue = {
  id: string;
  sceneId: SceneId;
  at: number;
  absolute: number;
  frame: number;
  absoluteFrame: number;
  kind: string;
  label: string;
  synthetic?: boolean;
};

type CueFile = {
  version: number;
  source: string;
  fps: number;
  cues: Cue[];
  scenes: Record<string, Cue[]>;
};

export const cueData = cueJson as unknown as CueFile;
export const cueSource = cueData.source;

export const cuesFor = (sceneId: SceneId): Cue[] =>
  (cueData.scenes[sceneId] ?? []).slice().sort((a, b) => a.at - b.at);

export const cueAt = (sceneId: SceneId, index: number): Cue | undefined =>
  cuesFor(sceneId)[index];

/**
 * Absolute frame of the Nth cue in a scene. If the cue sheet has fewer cues
 * than the scene asks for, fall back to the nominal offset in seconds.
 */
export const cueAbsoluteFrame = (
  sceneId: SceneId,
  index: number,
  fallbackAt = 0,
): number => {
  const cue = cueAt(sceneId, index);
  if (cue) {
    return cue.absoluteFrame;
  }
  const scene = sceneById(sceneId);
  return Math.round(((scene?.start ?? 0) + fallbackAt) * v2Script.fps);
};

export type CueState = {
  /** Cue frame relative to the picture sequence (can be negative on a J-cut). */
  frame: number;
  /** Frames elapsed since the cue fired. Negative before it fires. */
  since: number;
  /** 0..1 ramp after the cue fires. */
  progress: number;
  active: boolean;
  id: string;
  label: string;
  kind: string;
};

type UseCueOptions = {
  sceneId: SceneId;
  /** Absolute frame where the picture sequence starts. */
  sequenceFrom: number;
  index: number;
  fallbackAt?: number;
  ramp?: number;
};

/**
 * Reads the cue table generated by scripts/sync-v2.cjs from the existing v1
 * George VO timestamps and returns a frame-accurate trigger for overlays,
 * zooms, stamps and figure bounces.
 */
export const useCue = ({
  sceneId,
  sequenceFrom,
  index,
  fallbackAt = 0,
  ramp = 12,
}: UseCueOptions): CueState => {
  const frame = useCurrentFrame();
  const { fps } = useVideoConfig();
  const cue = cueAt(sceneId, index);
  const absolute = cueAbsoluteFrame(sceneId, index, fallbackAt);
  const local = absolute - sequenceFrom;
  const since = frame - local;
  const progress = interpolate(since, [0, Math.max(1, Math.round(ramp * (fps / 30)))], [0, 1], CLAMP);
  return {
    frame: local,
    since,
    progress,
    active: since >= 0,
    id: cue?.id ?? `${sceneId}.fallback-${index}`,
    label: cue?.label ?? '',
    kind: cue?.kind ?? 'cue',
  };
};

/** Convenience for non-hook code (e.g. computing beat sheets up front). */
export const cueTimes = (sceneId: SceneId): number[] =>
  cuesFor(sceneId).map((cue) => cue.absoluteFrame);
